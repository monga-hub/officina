import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createServer } from 'vite';
import { createServer as createHttpServer } from 'node:http';
import { defaults } from '../src/lab/config.js';
const server=await createServer({configFile:false,server:{middlewareMode:true,hmr:{server:createHttpServer()},watch:null},optimizeDeps:{noDiscovery:true,entries:[]},appType:'custom'});
try {
  const {Amount,MachineEffect,Development}=await server.ssrLoadModule('/src/lab/GameSymbols.jsx');
  const render=(component,props)=>renderToStaticMarkup(React.createElement(component,props));
  const {default:RoundsEditor}=await server.ssrLoadModule('/src/lab/RoundsEditor.jsx');
  const {mainDefaults,gameConfig}=await server.ssrLoadModule('/src/lab/config.js');
  assert.match(render(RoundsEditor,{c:mainDefaults(),set(){}}),/Ricambio dei mazzi operai/);
  const {initGame,legalCommands}=await server.ssrLoadModule('/src/game/engine.js');
  const {beginRoundRondel}=await server.ssrLoadModule('/src/game/round-rondel.js');
  const {default:Rondel}=await server.ssrLoadModule('/src/components/WelfareRondel.jsx');
  const {default:Board}=await server.ssrLoadModule('/src/lab/StarBoard.jsx');
  const {default:RoundChoice}=await server.ssrLoadModule('/src/components/RoundRondelChoice.jsx');
  const funds=initGame(gameConfig(mainDefaults()));
  const {default:Requests,RoundObjectivesDetails}=await server.ssrLoadModule('/src/lab/RoundObjectives.jsx');
  const requestStrip=render(Requests,{state:funds,player:funds.players[0],onInspect(){}});
  assert.match(requestStrip,/PV potenziali/);assert.match(requestStrip,/Scadenza T/);
  const requestDetails=render(RoundObjectivesDetails,{state:funds,player:funds.players[0]});
  assert.match(requestDetails,/Premi acquisiti/);assert.doesNotMatch(requestDetails,/da verificare|Provvisoria|Resta il riferimento/);

  const {default:Guided,welfareCommand}=await server.ssrLoadModule('/src/components/GuidedWelfareActions.jsx');
  const {welfareAllocations,WELFARE_FUNDS}=await server.ssrLoadModule('/src/game/welfare-funds.js');
  const purchases=[1,2,3].flatMap(count=>welfareAllocations(count).map(funds=>({type:'investWelfare',count,funds})));
  for(const c of purchases){
    const targets=WELFARE_FUNDS.flatMap(f=>Array(c.funds[f.id]).fill(f.id));
    assert.equal(welfareCommand(purchases,c.count,targets),c,'Every allocation selects the original legal command');
  }
  assert.equal(welfareCommand(purchases.filter(c=>c.count===1),3,['economy','economy','economy']),undefined);
  funds.phase='action';funds.players[0].node='Servizi';
  const welfareMenu=render(Guided,{state:funds,legal:purchases,dispatch(){}});
  assert.equal((welfareMenu.match(/<button/g)||[]).length,7,'Three fund counters and one confirmation replace nineteen allocation buttons');
  assert.ok(!welfareMenu.includes('<select'),'No dropdowns in Welfare');
  assert.match(welfareMenu,/<button class="primary" disabled=""/);
  const roles=Object.keys(funds.players[0].depts);
  for(const role of roles)funds.players[0].depts[role].tension=2;
  funds.roundRondel.funds.economy=3;funds.welfareBank=3;
  const repressions=roles.flatMap(role=>WELFARE_FUNDS.map(f=>({type:'repress',role,fund:f.id})));
  funds.players[0].node='Sindacato';
  const repressionMenu=render(Guided,{state:funds,legal:repressions,dispatch(){}});
  assert.equal((repressionMenu.match(/<button/g)||[]).length,7,'Department and fund buttons, then one confirmation');
  assert.match(repressionMenu,/potenziamenti si disattivano/);
  assert.ok(!repressionMenu.includes('<select'),'No dropdowns in repression');
  assert.equal((repressionMenu.match(/aria-pressed="true"/g)||[]).length,2);
  for(const role of roles)funds.players[0].depts[role].tension=0;
  funds.roundRondel.funds.economy=0;funds.welfareBank=0;funds.phase='move';funds.players[0].node='Citta';
  const rondel=render(Rondel,{state:funds,player:funds.players[0]});
  for(const id of ['economy','personnel','production'])assert.equal((rondel.match(new RegExp(`data-welfare-fund="${id}"`,'g'))||[]).length,id==='personnel'?3:2,'Affinity belongs to Personnel; other categories retain two policies');
  assert.match(rondel,/Affinità · Fondo Personale/);assert.match(rondel,/Innovazione · Fondo Economia/);assert.match(rondel,/Formazione · Fondo Personale/);assert.match(rondel,/Cooperazione · Fondo Produzione/);
  const bank=render(Board,{state:funds,dispatch(){}});
  for(const id of ['economy','personnel','production'])assert.ok(bank.includes(`data-welfare-fund="${id}"`),'Bank balances use the same category IDs');
  funds.turn=8;beginRoundRondel(funds,7);
  const choices=render(RoundChoice,{state:funds,player:funds.players[funds.current],legal:legalCommands(funds),dispatch(){}});
  for(const id of ['economy','personnel','production'])assert.equal((choices.match(new RegExp(`data-welfare-fund="${id}"`,'g'))||[]).length,2,'Round choices use the same pairing');
  const {default:TurnTrack}=await server.ssrLoadModule('/src/lab/TurnTrack.jsx');
  const timeline=render(TurnTrack,{state:{turn:14,roundLimit:28,roundRondel:{bounds:[9,18]}}});
  assert.equal((timeline.match(/<li\b/g)||[]).length,28);
  assert.equal((timeline.match(/↻ Rondella/g)||[]).length,2);
  assert.match(timeline,/aria-current="step"[^>]*>14<\/li>/);
  assert.match(timeline,/Turno 9 · Fine periodo/);assert.match(timeline,/Turno 18 · Fine periodo/);assert.match(timeline,/Turno 28 · Fine partita/);
  assert.match(render(TurnTrack,{state:{turn:10,roundLimit:28,roundRondel:{bounds:[9,18],active:{endTurn:9}}}}),/aria-current="step"[^>]*>9<\/li>/);
  const quarters=render(TurnTrack,{state:{turn:15,roundLimit:28,roundRondel:{bounds:[7,14,21]}}});
  assert.equal((quarters.match(/↻ Rondella/g)||[]).length,3);
  for(const end of [7,14,21])assert.ok(quarters.includes(`Turno ${end} · Fine periodo`));
  assert.match(quarters,/4° periodo/);
  assert.match(render(Amount,{kind:'coin',value:0}),/aria-label="0 marchi"/);
  assert.match(render(Amount,{kind:'pv',value:15}),/class="amount-token amount-pv"/);
  assert.match(render(Amount,{kind:'pv',value:15}),/>15<\/span>/);
  assert.match(render(Development,{value:4}),/sviluppo \+4/);
  const cards=defaults().workers;
  for(const worker of cards){const html=render(MachineEffect,{worker});assert.ok(!/undefined|NaN/.test(html),worker.id);}
  const tensionCard=cards.find(w=>w.effect.verbo==='perOgni'&&w.effect.f2?.conta==='tensione');
  const tensionHtml=render(MachineEffect,{worker:tensionCard});
  assert.match(tensionHtml,/>T<\/span>/);assert.match(tensionHtml,/tensione prima della produzione/);
  const conversion={sector:'Chimica',effect:{verbo:'scambia',f1:{q:2,tipo:'risorsa',settore:'scelta'},f2:{q:3,tipo:'moneta'}}};
  const html=render(MachineEffect,{worker:conversion});
  assert.match(html,/2 risorse a scelta → 3 marchi/);
  assert.ok(html.indexOf('amount-choice')<html.indexOf('amount-coin'),'Resource payment must precede the coin reward');
  const local=render(MachineEffect,{worker:{sector:'Chimica',effect:{verbo:'prendi',f1:{q:2,tipo:'risorsa',settore:'carta'}}}});
  assert.match(local,/resource-Coloranti/);
  console.log('OK: symbol quantities, free entry, PV, every current machine, choice conversions and card-sector resources.');
} finally { await server.close(); }
