import assert from 'node:assert/strict';
import {defaults,gameConfig,parseConfig} from '../src/lab/config.js';
import {WELFARE_POLICIES,welfarePolicy,welfareRondelCommands} from '../src/game/welfare-rondel.js';
import {initGame,applyCommand,legalCommands,forkForSearch,WORKER_BY_ID} from '../src/game/engine.js';
import {chooseCommand} from '../src/game/ai.js';
import {runGame,textReport} from '../src/lab/run.js';
import {saveGame,loadGame,gameSession} from '../src/lab/saved-game.js';
const c=defaults();c.welfareRondel=true;c.welfarePoliciesEnabled.formation=false;c.simulation.ai='greedy';
assert.deepEqual(parseConfig(JSON.stringify(c)),c);
const legacy=structuredClone(c);delete legacy.welfarePoliciesEnabled;
assert.ok(Object.values(parseConfig(JSON.stringify(legacy)).welfarePoliciesEnabled).every(Boolean));
const custom=structuredClone(c);custom.contractCount[3].small=5;assert.equal(parseConfig(JSON.stringify(custom)).contractCount[3].small,5);
for(const bad of [null,[],{}, {...c.welfarePoliciesEnabled,formation:1},{...c.welfarePoliciesEnabled,other:true}])assert.throws(()=>gameConfig({...c,welfarePoliciesEnabled:bad}),/ON\/OFF/);
for(const players of [2,3,4]) {
 const cfg=gameConfig({...c,players}),s=initGame(cfg);
 for(const size of ['small','medium','large'])assert.equal(s.contracts[size].deck.length+s.contracts[size].active.length,c.contracts[size].length,'All available contracts are in the shuffled deck/market');
}
const cfg=gameConfig(c),s=initGame(cfg),p=s.players[0];s.phase='action';p.node='Servizi';p.coins=20;
const commands=legalCommands(s).filter(c=>c.type==='investWelfare');assert.equal(commands.length,3);assert.ok(commands.every(c=>c.position!==0));
assert.throws(()=>applyCommand(s,{type:'investWelfare',steps:1,position:0}),/non disponibile/);
p.welfarePosition=5;
const nextCommands=welfareRondelCommands(s,p);assert.ok(!nextCommands.some(c=>c.steps===1));
assert.deepEqual(nextCommands.find(c=>c.steps===2),{type:'investWelfare',steps:2,position:1},'OFF space is traversed and still costs one step');
assert.ok(nextCommands.every(c=>c.steps<=3),'Maximum three steps, including traversed OFF spaces');
p.welfarePosition=0;assert.equal(welfarePolicy(s,p),null,'A disabled policy never grants its bonus');
s.phase='action';p.node='Tessile';const w=Object.values(WORKER_BY_ID).find(w=>w.sector==='Tessile'&&w.v===3);s.banks[s.nodeBanks.Tessile[0]]=[w.id];
const hire=legalCommands(s).find(c=>c.type==='hire'&&c.side==='sopra');assert.ok(hire);
assert.equal(applyCommand(s,hire).players[0].depts.terziario.prod,4,'No extra development from disabled Formation');
assert.equal(applyCommand(forkForSearch(s),hire).players[0].depts.terziario.prod,4);
const disabled=structuredClone(s);disabled.rowEconomy.welfarePoliciesEnabled=Object.fromEntries(WELFARE_POLICIES.map(p=>[p.id,false]));disabled.players[0].node='Servizi';
assert.ok(!legalCommands(disabled).some(c=>c.type==='investWelfare'));
const ai=structuredClone(s);ai.aiRollout={depth:2,rollouts:1};assert.ok(chooseCommand(ai));
let stored;saveGame(cfg,{state:s,history:[],paused:true},{setItem:(k,v)=>stored=v});
assert.equal(gameSession(cfg,loadGame({getItem:()=>stored})).state.rowEconomy.welfarePoliciesEnabled.formation,false);
const editor={...c,players:3,turns:6};const game=await runGame(gameConfig(editor));
assert.deepEqual(game.study.verified,{completed:true,money:3,resources:3,machineIncome:3});
assert.ok(game.finalState.players.every(p=>p.welfareRondelStats.benefits.formation===0&&p.welfareRondelStats.visits.every(v=>v.position!==0)));
const report=textReport(editor,[game],'Completata');assert.ok(report.includes('| Formazione | OFF |'));assert.ok(report.includes('small 12/12'));
console.log('OK: policy switches affect destinations/bonuses/AI, disabled spaces retain distances, all-OFF handling, legacy import, save, forecast, verified game/report and complete shuffled contract defaults for 2/3/4 players.');
